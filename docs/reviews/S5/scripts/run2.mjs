import { chromium } from 'playwright';
const OUT = '/Users/padoa/Programs/spot-elec-wt/v2-lab/docs/reviews/S5';
const BASE = 'http://localhost:5173/dispatch/lab.html';
const b = await chromium.launch({ channel: 'chrome' });
const p = await (await b.newContext({ viewport: { width: 1280, height: 900 } })).newPage();
const errs = []; p.on('pageerror', (e) => errs.push(e.message));
await p.goto(BASE + '#/'); await p.waitForSelector('#lab-lot');
await p.selectOption('#lab-lot', 't1'); await p.waitForTimeout(600);
await p.screenshot({ path: OUT + '/list-generated-lot-1280.png', fullPage: true });
await p.click('[data-play="0"]'); await p.waitForSelector('.board-svg'); await p.waitForTimeout(2500);
console.log('strip:', (await p.textContent('.lab-strip')).replace(/\s+/g, ' '));
await p.screenshot({ path: OUT + '/play-generated-1280.png' });
await p.click('#lab-giveup'); await p.waitForURL(/#\/fin\/t1\/0/); await p.waitForTimeout(300);
console.log('end head:', (await p.textContent('.lab-head')).replace(/\s+/g, ' '));
await p.click('#lab-new').catch(() => {});
await p.goto(BASE + '#/'); await p.waitForSelector('#lab-new'); await p.click('#lab-new'); await p.waitForTimeout(200);
await p.screenshot({ path: OUT + '/new-lot-form-1280.png', fullPage: true });
console.log('errors', errs);
await b.close();
