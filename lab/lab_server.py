PLAY_SCHEMA = 1
PHANTOM_MS = 10_000  # an abandon shorter than this, or without any move, is a stray open, not an attempt
# Solver measures hidden from a player who has not rated the candidate yet.
HIDDEN_PLAY_KEYS = ("outcome", "ms", "wall_ms", "errors", "undos", "erasers", "resets", "moves", "felt")
DEFAULT_SESSION_SIZE = 16
COUNTERS_FILE = ".counters.json"  # last session number per lot, in lab/sessions/ (not a session)
UNKNOWN_AUTHOR = ""  # key of a comment written before comments were stored per player, whose author is unknown


class LabError(Exception):
    def __init__(self, message: str, status: int = 400):
        super().__init__(message)
        self.status = status


def default_checker(grid: dict[str, Any]) -> dict[str, Any]:
    """Grid check through the solver package (validity, uniqueness, deduction)."""
    try:
        from dispatch_solver.api import check_grid
    except ImportError as e:  # pragma: no cover - depends on the environment
        raise LabError(f"dispatch_solver is not installed: {e}", 501) from e
    return check_grid(grid, allow_ramp=True)


def default_runner(lot_path: Path, out_dir: Path, log: Callable[[str], None]) -> int:
    """Run the generator CLI, streaming its stderr lines to `log`."""
    proc = subprocess.Popen(
        [sys.executable, "-m", "dispatch_solver.cli", "generate", str(lot_path), "--out", str(out_dir)],
        stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True,
    )
    assert proc.stdout is not None
    for line in proc.stdout:
        log(line.rstrip())
    return proc.wait()


PLAYABLE_SHAPES = {"rect", "trap"}


def has_ramp(g: dict[str, Any]) -> bool:
    """Shapes the web game cannot play: only rectangles and trapezoid ramps are supported (staircase is not)."""
    return any(
        isinstance(p, dict) and p.get("shape", "rect") not in PLAYABLE_SHAPES for p in g.get("pieces", {}).values()
    )


def draw_session(pool: list[tuple[int, dict[str, Any]]], size: int, rng: random.Random) -> list[int]:
    """Pick `size` candidate indexes from `pool` and order them (see Lab.create_session)."""
    def rating(g: dict[str, Any]) -> int:
        return int(g["difficulty"]["rating"])

    def tags(g: dict[str, Any]) -> list[str]:
        lab = g.get("lab", {})
        return [f"f:{lab.get('family')}"] + [f"m:{str(m).split(':')[0]}" for m in lab.get("mechanics", [])]

    left: dict[int, list[tuple[int, dict[str, Any]]]] = {}
    for item in sorted(pool, key=lambda t: t[0]):
        left.setdefault(rating(item[1]), []).append(item)
    seen: dict[str, int] = {}
    picked: dict[int, list[int]] = {r: [] for r in left}
    # Round-robin over the ratings: equal counts when possible, the rest shared by the ratings that still have candidates.
    remaining = size
    while remaining:
        for r in rng.sample(sorted(left), len(left)):
            if not remaining:
                break
            if not left[r]:
                continue
            best = min(left[r], key=lambda t: (sum(seen.get(x, 0) for x in tags(t[1])), rng.random()))
            left[r].remove(best)
            picked[r].append(best[0])
            for x in tags(best[1]):
                seen[x] = seen.get(x, 0) + 1
            remaining -= 1
    # Order: a random permutation (seeded), the only constraint being an easiest grid first. No rule on neighbours:
    # any structure in the order would let the player guess the rating of the next grid.
    pool_left = [i for r in picked for i in picked[r]]
    lowest = min(r for r in picked if picked[r])
    first = rng.choice(picked[lowest])
    rest = [i for i in pool_left if i != first]
    rng.shuffle(rest)
    out = [first] + rest
    return out


class Lab:
    """Files and rules of the lab; the HTTP layer only calls these methods."""

    def __init__(self, lab_dir: Path, grids_path: Path, checker=default_checker, runner=default_runner):
        self.dir = lab_dir
        self.grids_path = grids_path
        self.checker = checker
        self.runner = runner
        self.lock = threading.RLock()
        self.jobs: dict[str, dict[str, Any]] = {}
        for sub in ("candidates", "lots", "sessions"):
            (self.dir / sub).mkdir(parents=True, exist_ok=True)

    # ---- small file helpers
    def _read_json(self, path: Path, default: Any) -> Any:
        try:
            return json.loads(path.read_text())
        except FileNotFoundError:
            return default

    def _write_json(self, path: Path, data: Any, indent: int = 1) -> None:
        tmp = path.with_suffix(path.suffix + ".tmp")
        tmp.write_text(json.dumps(data, ensure_ascii=False, indent=indent) + "\n")
        tmp.replace(path)

    @staticmethod
    def _name(value: str) -> str:
        if not SAFE_NAME.match(value or ""):
            raise LabError(f"invalid name: {value!r}")
        return value

    # ---- players, lots, candidates
    def players(self) -> list[str]:
        data = self._read_json(self.dir / "players.json", None)
        return data if isinstance(data, list) and data else list(PLAYERS)

    def lots(self) -> list[dict[str, Any]]:
        out = []
        for f in sorted((self.dir / "candidates").glob("*.json")):
            if f.name.endswith((".stats.json", ".blocked.json")):
                continue
            grids = self._read_json(f, [])
            stats = self._read_json(f.with_suffix(".stats.json"), None)
            out.append({"lot": f.stem, "count": len(grids), "stats": stats})
        return out

    def _grids(self, lot: str) -> list[dict[str, Any]]:
        path = self.dir / "candidates" / f"{self._name(lot)}.json"
        if not path.exists():
            raise LabError(f"unknown lot {lot}", 404)
        return self._read_json(path, [])

    @staticmethod
    def _index(g: dict[str, Any], position: int) -> int:
        return int(g.get("lab", {}).get("index", position))

    def _find(self, lot: str, index: int) -> dict[str, Any]:
        for pos, g in enumerate(self._grids(lot)):
            if self._index(g, pos) == index:
                return g
        raise LabError(f"no candidate {index} in lot {lot}", 404)

    def revealed(self, lot: str, index: int, player: str | None, plays: list[dict[str, Any]] | None = None,
                 notes: dict[str, Any] | None = None) -> bool:
        """True once `player` has rated this candidate (then the solver measures may be shown to them)."""
        if not player:
            return False
        notes = self.notes() if notes is None else notes
        if player in notes.get(f"{lot}:{index}", {}).get("felt", {}):
            return True
        plays = self.plays(lot) if plays is None else plays
        return any(p["index"] == index and p["player"] == player and p.get("felt") for p in plays)

    def candidates(self, lot: str, player: str | None = None, creation: bool = False) -> list[dict[str, Any]]:
        """Candidates for the list screen; rating, techniques, steps and felt ratings only once revealed to `player`."""
        notes = self._read_json(self.dir / "notes.json", {})
        plays = self.plays(lot)
        out = []
        for pos, g in enumerate(self._grids(lot)):
            index = self._index(g, pos)
            note = notes.get(f"{lot}:{index}", {})
            mine = [p for p in plays if p["index"] == index]
            lab = g.get("lab", {})
            show = creation or self.revealed(lot, index, player, plays, notes)
            trace = lab.get("trace_summary", {})
            out.append({
                "lot": lot, "index": index, "title": g.get("title") if show else f"Candidate {index + 1}",
                "cols": len(g["columns"]), "clues": len(g["clues"]),
                "clue_source": {k: g[k] for k in ("clues", "inventory", "step") if k in g},
                "revealed": show,
                "rating": g.get("difficulty", {}).get("rating") if show else None,
                "techniques": g.get("difficulty", {}).get("techniques", []) if show else [],
                "family": lab.get("family"), "mechanics": lab.get("mechanics", []),
                "clue_profile": lab.get("clue_profile", []), "trace_summary": trace if show else {},
                "silhouette": g["demand"], "playable": not has_ramp(g), "plays": len(mine),
                "kept": bool(note.get("kept")), "felt": note.get("felt", {}) if show else {},
                "promoted": note.get("promoted"),
            })
        return out

    def blind_grid(self, lot: str, index: int) -> dict[str, Any]:
        """Grid for playing: no `lab` block, solver rating, techniques or bulletin text."""
        g = copy.deepcopy(self._find(lot, index))
        if has_ramp(g):
            raise LabError("staircase ramps cannot be played in the web game yet", 422)
        g.pop("lab", None)
        g.pop("bulletin", None)
        if not isinstance(g.get("id"), int) or g["id"] < 1:
            g["id"] = index + 1
        g["section"] = "rated"
        g["title"] = f"Candidate {index + 1}"
        g["difficulty"] = {"rating": 1, "label": "Candidate", "techniques": []}
        g.pop("intro", None)
        g.pop("teaches", None)
        return g

    def full_grid(self, lot: str, index: int) -> dict[str, Any]:
        return self._find(lot, index)

    # ---- sessions (ordered candidates to play in a row)
    def sessions(self) -> list[dict[str, Any]]:
        out = []
        loaded = [(f, self._read_json(f, {})) for f in (self.dir / "sessions").glob("*.json") if not f.name.startswith(".")]
        # Most recent first: the creation time stored in the file, else the file time (hand-written sessions).
        loaded.sort(key=lambda fd: (fd[1].get("created") or fd[0].stat().st_mtime, fd[0].name), reverse=True)
        for f, data in loaded:
            out.append({"id": f.stem, "title": data.get("title", f.stem), "count": len(data.get("items", []))})
        return out

    def session(self, session_id: str, player: str | None) -> dict[str, Any]:
        """A session with the state of each item for `player`: solved, abandoned or todo (phantom plays ignored).

        Nothing but lot, number, state and the optional `hold` text is sent: no note, technique or draft title.
        """
        path = self.dir / "sessions" / f"{self._name(session_id)}.json"
        if session_id.startswith(".") or not path.exists():
            raise LabError(f"unknown session {session_id}", 404)
        data = self._read_json(path, {})
        plays = [p for p in self.plays() if p.get("player") == player and not p.get("phantom")]
        items = []
        for pos, it in enumerate(data.get("items", [])):
            lot, index = str(it["lot"]), int(it["index"])
            mine = [p for p in plays if p.get("lot") == lot and p.get("index") == index]
            state = "solved" if any(p.get("outcome") == "solved" for p in mine) else "abandoned" if mine else "todo"
            try:
                playable = not has_ramp(self._find(lot, index))
            except LabError:
                playable = False
            item: dict[str, Any] = {"position": pos + 1, "lot": lot, "index": index, "number": index + 1,
                                    "state": state, "attempts": len(mine), "playable": playable}
            if it.get("hold"):
                item["hold"] = str(it["hold"])
            items.append(item)
        return {"id": session_id, "title": data.get("title", session_id), "items": items}

    def create_session(self, lot: str, size: Any = None, player: str | None = None) -> dict[str, Any]:
        """Draw a session from a lot and write lab/sessions/<lot>-<n>.json (`n` never reused).

        Deterministic (seed = lot name + n). Balanced by solver rating (same count per rating when possible), then by
        family and mechanics; candidates already played by `player` (non-phantom) are left out. The order starts with
        the lowest rating and never repeats a rating twice in a row when possible. The solver rating is used here only:
        the file and the answer carry lot and index, nothing else.
        """
        size = DEFAULT_SESSION_SIZE if size is None else size
        if not isinstance(size, int) or isinstance(size, bool) or size < 1:
            raise LabError("size must be a positive integer")
        if player is not None and player not in self.players():
            raise LabError(f"unknown player {player!r}")
        grids = self._grids(lot)
        with self.lock:
            played = {p["index"] for p in self.plays(lot) if p.get("player") == player and not p.get("phantom")
                      and p.get("attempt", 1) >= 1} if player else set()
            pool = [(self._index(g, pos), g) for pos, g in enumerate(grids) if not has_ramp(g)]
            pool = [(i, g) for i, g in pool if i not in played and g.get("difficulty", {}).get("rating")]  # unrated: cannot be balanced
            if not pool:
                raise LabError(f"lot {lot} has no candidate left to play", 409)
            sessions_dir = self.dir / "sessions"
            used = [int(m.group(1)) for f in sessions_dir.glob(f"{lot}-*.json") if (m := re.fullmatch(rf"{re.escape(lot)}-(\d+)", f.stem))]
            counters_path = sessions_dir / COUNTERS_FILE
            counters = self._read_json(counters_path, {})
            n = max(used + [int(counters.get(lot, 0))]) + 1  # the last n of a lot is remembered: a name is never handed out twice
            counters[lot] = n
            self._write_json(counters_path, counters)
            order = draw_session(pool, min(size, len(pool)), random.Random(f"{lot}:{n}"))
            session_id = f"{lot}-{n}"
            self._write_json(sessions_dir / f"{session_id}.json",
                             {"title": f"Session {lot} n° {n}", "created": time.time(), "items": [{"lot": lot, "index": i} for i in order]})
        return self.session(session_id, player)

    # ---- plays
    @staticmethod
    def grid_hash(g: dict[str, Any]) -> str:
        """sha1 of the grid without its `lab` block: ties a play to the exact grid that was played."""
        body = {k: v for k, v in g.items() if k != "lab"}
        return hashlib.sha1(json.dumps(body, sort_keys=True, ensure_ascii=False).encode()).hexdigest()

    def plays(self, lot: str | None = None) -> list[dict[str, Any]]:
        path = self.dir / "plays.jsonl"
        if not path.exists():
            return []
        out = []
        for line in path.read_text().splitlines():
            if not line.strip():
                continue
            try:
                p = json.loads(line)
            except json.JSONDecodeError:
                continue
            if lot is None or p.get("lot") == lot:
                out.append(p)
        return out

    def plays_for(self, lot: str | None, player: str | None, creation: bool = False) -> list[dict[str, Any]]:
        """Plays with the measures of other players hidden on candidates not yet rated by `player`."""
        plays = self.plays(lot)
        if creation:
            return plays
        notes = self.notes()
        cache: dict[tuple[str, int], bool] = {}
        out = []
        for p in plays:
            key = (p["lot"], p["index"])
            if key not in cache:
                cache[key] = self.revealed(p["lot"], p["index"], player, plays, notes)
            if cache[key] or p["player"] == player:
                out.append(p)
            else:
                out.append({k: v for k, v in p.items() if k not in HIDDEN_PLAY_KEYS} | {"masked": True})
        return out

    def add_play(self, body: dict[str, Any]) -> dict[str, Any]:
        player = body.get("player")
        if player not in self.players():
            raise LabError(f"unknown player {player!r}")
        lot, index = str(body.get("lot")), int(body.get("index", -1))
        grid = self._find(lot, index)
        if body.get("outcome") not in OUTCOMES:
            raise LabError("outcome must be solved or abandoned")
        now = int(time.time())
        play: dict[str, Any] = {
            "schema": PLAY_SCHEMA, "id": uuid.uuid4().hex, "player": player, "lot": lot, "index": index,
            "grid_hash": self.grid_hash(grid), "outcome": body["outcome"], "ts": now,
        }
        for key in ("ms", "errors", "undos", "erasers", "resets", "moves"):
            value = body.get(key, 0)
            if not isinstance(value, int) or isinstance(value, bool) or value < 0:
                raise LabError(f"{key} must be a non-negative integer")
            play[key] = value
        wall = body.get("wall_ms", play["ms"])
        if not isinstance(wall, int) or isinstance(wall, bool) or wall < play["ms"]:
            raise LabError("wall_ms must be an integer >= ms")
        play["wall_ms"] = wall
        started = body.get("started", now - round(wall / 1000))
        if not isinstance(started, int) or isinstance(started, bool) or started <= 0:
            raise LabError("started must be a positive integer (epoch seconds)")
        play["started"] = started
        play["reason"] = body.get("reason") if body.get("reason") in ("unload",) else None
        # A stray open (abandoned with no move, or within the first seconds) is not an attempt.
        no_move = "moves" in body and play["moves"] == 0
        play["phantom"] = play["outcome"] == "abandoned" and (no_move or play["ms"] < PHANTOM_MS)
        with self.lock:
            earlier = [p for p in self.plays(lot) if p["index"] == index and p["player"] == player
                       and p.get("grid_hash", play["grid_hash"]) == play["grid_hash"] and not p.get("phantom")]
            play["attempt"] = len(earlier) + 1
            play["felt"] = None
            with open(self.dir / "plays.jsonl", "a") as f:
                f.write(json.dumps(play, ensure_ascii=False) + "\n")
        return play

    def rate_play(self, play_id: str, felt: Any, comment: Any = None) -> dict[str, Any]:
        """Attach the felt rating (and comment) to a play, once; the first rating of a player also goes to the notes."""
        if felt not in (1, 2, 3, 4) or isinstance(felt, bool):
            raise LabError("felt must be 1, 2, 3 or 4")
        with self.lock:
            path = self.dir / "plays.jsonl"
            rows = path.read_text().splitlines() if path.exists() else []
            target = None
            for n, line in enumerate(rows):
                try:
                    p = json.loads(line)
                except json.JSONDecodeError:
                    continue
                if p.get("id") == play_id:
                    target, at = p, n
                    break
            if target is None:
                raise LabError("unknown play", 404)
            if target.get("felt"):
                raise LabError("this play is already rated", 409)
            target["felt"] = felt
            rows[at] = json.dumps(target, ensure_ascii=False)
            tmp = path.with_suffix(".jsonl.tmp")
            tmp.write_text("\n".join(rows) + "\n")
            tmp.replace(path)
            notes = self.notes()
            note = notes.setdefault(f"{target['lot']}:{target['index']}", {})
            note.setdefault("felt", {}).setdefault(target["player"], felt)
            if comment is not None:
                self._set_comment(note, target["player"], comment)
            self._write_json(self.dir / "notes.json", notes)
            return target

    # ---- notes (kept, felt rating, comment, bulletin edits)
    def notes(self) -> dict[str, Any]:
        notes = self._read_json(self.dir / "notes.json", {})
        for note in notes.values():
            self._migrate_comment(note)
        return notes

    @staticmethod
    def _migrate_comment(note: dict[str, Any]) -> None:
        """A single-string comment (older notes) becomes {player: text}: its author when only one player has rated."""
        text = note.get("comment")
        if not isinstance(text, str):
            return
        raters = list(note.get("felt", {}))
        if text:
            note["comment"] = {raters[0] if len(raters) == 1 else UNKNOWN_AUTHOR: text}
        else:
            note.pop("comment")

    @staticmethod
    def _set_comment(note: dict[str, Any], player: str, text: Any) -> None:
        """One comment per player; an empty text removes the player's comment, never another player's."""
        comments = note.setdefault("comment", {})
        if str(text).strip():
            comments[player] = str(text)
        else:
            comments.pop(player, None)
        if not comments:
            note.pop("comment")

    def notes_for(self, player: str | None, creation: bool = False) -> dict[str, Any]:
        """Notes; felt ratings and other players' comments only for candidates already revealed to `player`."""
        notes = self.notes()
        if creation:
            return notes
        plays = self.plays()
        out = {}
        for key, note in notes.items():
            lot, _, index = key.rpartition(":")
            note = dict(note)
            if ("felt" in note or "comment" in note) and not self.revealed(lot, int(index), player, plays, notes):
                note.pop("felt", None)
                own = {p: c for p, c in note.pop("comment", {}).items() if p == player}
                if own:
                    note["comment"] = own
            out[key] = note
        return out

    def update_note(self, lot: str, index: int, patch: dict[str, Any]) -> dict[str, Any]:
        """Kept flag, comment of `patch["player"]` and bulletin edits (felt ratings go through rate_play)."""
        self._find(lot, index)
        key = f"{lot}:{index}"
        with self.lock:
            notes = self.notes()
            note = notes.setdefault(key, {})
            if "kept" in patch:
                note["kept"] = bool(patch["kept"])
            if "comment" in patch:
                if patch.get("player") not in self.players():
                    raise LabError("a comment needs a known player")
                self._set_comment(note, patch["player"], patch["comment"])
            if "bulletin" in patch:
                if note.get("promoted"):
                    raise LabError("this candidate is already promoted: edit grids.json instead", 409)
                note["bulletin"] = self._bulletin_patch(patch["bulletin"])
            self._write_json(self.dir / "notes.json", notes)
            return note

    @staticmethod
    def _bulletin_patch(b: dict[str, Any]) -> dict[str, Any]:
        out: dict[str, Any] = {}
        if not isinstance(b, dict):
            raise LabError("bulletin must be an object")
        for key in ("title", "text"):
            if key in b:
                out[key] = str(b[key])
        if "weather" in b:
            if not isinstance(b["weather"], list) or any(w not in ("sun", "moon", "cloud", "wind") for w in b["weather"]):
                raise LabError("weather must be a list of sun, moon, cloud or wind")
            out["weather"] = b["weather"]
        return out

    def bulletin_of(self, lot: str, index: int) -> dict[str, Any]:
        """Draft from the generator, overridden by the human's edits."""
        g = self._find(lot, index)
        draft = dict(g.get("lab", {}).get("bulletin") or {})
        draft.update(self.notes().get(f"{lot}:{index}", {}).get("bulletin", {}))
        return draft

    # ---- promotion
    def published(self) -> list[dict[str, Any]]:
        return self._read_json(self.grids_path, [])

    def suggest(self) -> dict[str, Any]:
        grids = self.published()
        numbers = [g["bulletin"]["number"] for g in grids if g.get("bulletin")]
        days = [g["bulletin"]["published"] for g in grids if g.get("bulletin")]
        last_day = max(days) if days else None
        next_day = (date.fromisoformat(last_day) + timedelta(days=1)) if last_day else date.today()
        return {"id": max((g["id"] for g in grids), default=0) + 1,
                "number": max(numbers, default=0) + 1, "published": next_day.isoformat()}

    def promote(self, lot: str, index: int, number: int, published: str, id_: int | None = None) -> dict[str, Any]:
        with self.lock:
            notes = self.notes()
            key = f"{lot}:{index}"
            if notes.get(key, {}).get("promoted"):
                raise LabError("this candidate is already promoted", 409)
            try:
                date.fromisoformat(published)
            except ValueError as e:
                raise LabError("published must be a date YYYY-MM-DD") from e
            grids = self.published()
            if any(g.get("bulletin", {}).get("number") == number for g in grids):
                raise LabError(f"bulletin number {number} is already used", 409)
            if any(g.get("bulletin", {}).get("published") == published for g in grids):
                raise LabError(f"publication date {published} is already taken", 409)
            if any((g["bulletin"]["number"] < number) != (g["bulletin"]["published"] < published)
                   for g in grids if g.get("bulletin")):
                raise LabError("bulletin numbers and publication dates must grow together", 409)
            if id_ is not None and (not isinstance(id_, int) or isinstance(id_, bool)):
                raise LabError("id must be an integer")
            new_id = id_ if id_ is not None else max((g["id"] for g in grids), default=0) + 1
            if any(g["id"] == new_id for g in grids):
                raise LabError(f"grid id {new_id} is already used", 409)
            grid = copy.deepcopy(self._find(lot, index))
            if has_ramp(grid):
                raise LabError("staircase ramps cannot be promoted until the game plays them", 422)
            grid.pop("lab", None)
            grid["id"] = new_id
            grid["section"] = "rated"
            bulletin = self.bulletin_of(lot, index)
            if not bulletin.get("title") or not bulletin.get("text") or not bulletin.get("weather"):
                raise LabError("the bulletin needs a title, a text and one weather per slot")
            if len(bulletin["weather"]) != len(grid["columns"]):
                raise LabError("the bulletin needs one weather per slot")
            grid["title"] = bulletin["title"]
            grid["bulletin"] = {"number": number, "title": bulletin["title"], "text": bulletin["text"],
                                "weather": bulletin["weather"], "published": published}
            report = self.checker(grid)
            if not report.get("valid", False):
                raise LabError("invalid grid: " + "; ".join(report.get("errors", [])))
            if (report.get("compositions") != 1 or report.get("deduction") != "solved"
                    or report.get("matches_reference") is not True):
                raise LabError(f"grid is not unique, deducible and equal to its reference solution (compositions="
                               f"{report.get('compositions')}, deduction={report.get('deduction')}, "
                               f"matches_reference={report.get('matches_reference')})", 422)
            self._write_json(self.grids_path, grids + [grid], indent=2)
            notes.setdefault(key, {})["promoted"] = {"id": new_id, "number": number, "published": published}
            self._write_json(self.dir / "notes.json", notes)
            return {"id": new_id, "number": number, "published": published}

    # ---- lot generation
    def start_generation(self, lot: dict[str, Any]) -> dict[str, Any]:
        name = self._name(str(lot.get("lot", "")))
        if not isinstance(lot.get("size"), int) or lot["size"] < 1:
            raise LabError("size must be a positive integer")
        if any(j["lot"] == name and j["status"] == "running" for j in self.jobs.values()):
            raise LabError(f"lot {name} is already being generated", 409)
        if (self.dir / "candidates" / f"{name}.json").exists():
            raise LabError(f"lot {name} already exists: pick another name", 409)
        path = self.dir / "lots" / f"{name}.json"
        self._write_json(path, lot)
        job = {"id": f"{name}-{int(time.time())}", "lot": name, "status": "running", "log": [], "started": time.time()}
        self.jobs[job["id"]] = job

        def work() -> None:
            try:
                code = self.runner(path, self.dir / "candidates", job["log"].append)
                produced = self.dir / "candidates" / f"{name}.json"
                job["code"] = code
                if code == 0:
                    job["status"] = "done"
                elif produced.exists():  # the CLI exits 1 on a partial lot but writes what it found
                    job["status"] = "partial"
                    job["kept"] = len(self._read_json(produced, []))
                    job["size"] = lot["size"]
                else:
                    job["status"] = "failed"
            except Exception as e:  # noqa: BLE001 - reported to the page
                job["log"].append(f"error: {e}")
                job["status"] = "failed"

        threading.Thread(target=work, daemon=True).start()
        return job

    def job(self, job_id: str) -> dict[str, Any]:
        if job_id not in self.jobs:
            raise LabError("unknown job", 404)
        return self.jobs[job_id]


def make_handler(lab: Lab, port: int = 0, vite_port: int = VITE_PORT):
    local = ("localhost", "127.0.0.1")
    hosts = {f"{h}:{p}" for h in local for p in (port, vite_port)}
    origins = {f"http://{h}:{vite_port}" for h in local} | {f"http://{h}:{port}" for h in local}

    class Handler(BaseHTTPRequestHandler):
        def log_message(self, *_args) -> None:  # quiet
            pass

        def _send(self, data: Any, status: int = 200) -> None:
            body = json.dumps(data, ensure_ascii=False).encode()
            self.send_response(status)
            self.send_header("Content-Type", "application/json; charset=utf-8")
            self.send_header("Content-Length", str(len(body)))
            self.end_headers()
            self.wfile.write(body)

        def _guard(self, method: str) -> None:
            """Refuse foreign hosts (DNS rebinding), foreign origins and non-JSON writes (cross-site forms)."""
            if self.headers.get("Host") not in hosts:
                raise LabError("host not allowed", 403)
            origin = self.headers.get("Origin")
            if origin is not None and origin not in origins:
                raise LabError("origin not allowed", 403)
            if method in ("POST", "PUT") and self.headers.get("Content-Type", "").split(";")[0].strip() != "application/json":
                raise LabError("Content-Type must be application/json", 415)

        def _body(self) -> dict[str, Any]:
            n = int(self.headers.get("Content-Length") or 0)
            try:
                data = json.loads(self.rfile.read(n) or b"{}")
            except json.JSONDecodeError as e:
                raise LabError(f"invalid JSON: {e}") from e
            if not isinstance(data, dict):
                raise LabError("body must be a JSON object")
            return data

        def _route(self, method: str) -> Any:
            url = urlparse(self.path)
            parts = [p for p in url.path.split("/") if p]
            q = {k: v[0] for k, v in parse_qs(url.query).items()}
            player, creation = q.get("player"), q.get("creation") == "1"
            if parts[:1] != ["api"]:
                raise LabError("not found", 404)
            r = parts[1:]
            if method == "GET":
                if r == ["players"]:
                    return lab.players()
                if r == ["lots"]:
                    return lab.lots()
                if r == ["candidates"]:
                    return lab.candidates(q.get("lot", ""), player, creation)
                if len(r) == 3 and r[0] == "grid":
                    return lab.blind_grid(r[1], int(r[2]))
                if len(r) == 3 and r[0] == "reveal":
                    lot, index = r[1], int(r[2])
                    g = lab.full_grid(lot, index)
                    if not (creation or lab.revealed(lot, index, player)):
                        raise LabError("rate this candidate first", 403)
                    return {"difficulty": g.get("difficulty"), "lab": g.get("lab", {}), "bulletin": lab.bulletin_of(lot, index),
                            "grid": g}
                if len(r) == 3 and r[0] == "bulletin":
                    return lab.bulletin_of(r[1], int(r[2]))
                if r == ["plays"]:
                    return lab.plays_for(q.get("lot"), player, creation)
                if r == ["notes"]:
                    return lab.notes_for(player, creation)
                if r == ["sessions"]:
                    return lab.sessions()
                if len(r) == 2 and r[0] == "session":
                    return lab.session(r[1], player)
                if r == ["suggest"]:
                    return lab.suggest()
                if len(r) == 2 and r[0] == "jobs":
                    return lab.job(r[1])
            elif method == "POST":
                if r == ["plays"]:
                    return lab.add_play(self._body())
                if len(r) == 3 and r[0] == "plays" and r[2] == "rate":
                    b = self._body()
                    return lab.rate_play(r[1], b.get("felt"), b.get("comment"))
                if r == ["sessions"]:
                    b = self._body()
                    return lab.create_session(str(b.get("lot", "")), b.get("size"), b.get("player"))
                if r == ["generate"]:
                    return lab.start_generation(self._body())
                if r == ["promote"]:
                    b = self._body()
                    return lab.promote(str(b.get("lot")), int(b.get("index", -1)), int(b.get("number", 0)),
                                       str(b.get("published", "")), b.get("id"))
            elif method == "PUT" and len(r) == 3 and r[0] == "notes":
                return lab.update_note(r[1], int(r[2]), self._body())
            raise LabError("not found", 404)

        def _handle(self, method: str) -> None:
            try:
                self._guard(method)
                self._send(self._route(method))
            except LabError as e:
                self._send({"error": str(e)}, e.status)
            except (ValueError, KeyError, TypeError, AttributeError) as e:
                self._send({"error": f"bad request: {e}"}, 400)

        def do_GET(self) -> None:
            self._handle("GET")

        def do_POST(self) -> None:
            self._handle("POST")

        def do_PUT(self) -> None:
            self._handle("PUT")

    return Handler


def serve(lab: Lab, port: int, host: str = "127.0.0.1", vite_port: int = VITE_PORT) -> ThreadingHTTPServer:
    server = ThreadingHTTPServer((host, port), make_handler(lab, port, vite_port))
    if port == 0:  # ephemeral port (tests): the handler needs the real one for the Host check
        server.RequestHandlerClass = make_handler(lab, server.server_address[1], vite_port)
    return server


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--port", type=int, default=8765)
    ap.add_argument("--lab-dir", default=str(ROOT / "lab"))
    ap.add_argument("--grids", default=str(ROOT / "web" / "src" / "data" / "grids.json"))
    a = ap.parse_args(argv)
    server = serve(Lab(Path(a.lab_dir), Path(a.grids)), a.port)
    print(f"lab server on http://127.0.0.1:{a.port}", flush=True)
    try:
        server.serve_forever()
    except KeyboardInterrupt:
        pass
    return 0


if __name__ == "__main__":
    sys.exit(main())
