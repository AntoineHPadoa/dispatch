"""Local lab server: JSON API over the files in lab/ (standard library only).

- Candidates: lab/candidates/<lot>.json (grids with a `lab` block, written by dispatch-solver).
- Plays: lab/plays.jsonl (one JSON line per game, format in lab/README.md); notes: lab/notes.json (kept, first felt rating and comment
  of each player, bulletin edits).
- Lots are generated by running `dispatch-solver generate` in a subprocess (needs dispatch_solver).
- Promotion: strips `lab`, gives id, bulletin number and date, checks the grid, appends it to grids.json.
- Sessions: lab/sessions/<id>.json (an ordered list of candidates to play, with the state of each for the current player);
  POST /api/sessions draws one from a lot (deterministic, balanced by solver rating then by family/mechanics, blind).
- Blind by player: solver rating, techniques, steps and the other player's measures are hidden until the player
  has rated the grid (or the page asks for creation mode).
- Writes need Content-Type application/json from a local origin; Host and Origin are checked.

Example: python lab/lab_server.py --port 8765   (the Vite dev server proxies /api to it)
"""

